/**
 * 从基准色向目标色按比例混合，用于补全 Arco 需要的十级色阶。
 *
 * @param base - 第 6 级（Arco 的默认主色位）取值。
 * @param toward - 混合目标色。
 * @param t - 混合比例，0 为完全取 `base`，1 为完全取 `toward`。
 * @returns 四舍五入到整数的三元组。
 */
export function mixTriple(base: Triple, toward: Triple, t: number): Triple {
  return [
    Math.round(base[0] * (1 - t) + toward[0] * t),
    Math.round(base[1] * (1 - t) + toward[1] * t),
    Math.round(base[2] * (1 - t) + toward[2] * t),
  ]
}

/** 白色与黑色，供 {@link ramp} 白化、黑化使用。 */
export const WHITE: Triple = [255, 255, 255]
/** 黑色。 */
export const BLACK: Triple = [0, 0, 0]

/**
 * 以第 6 级基准色展开 Arco 的十级色阶。
 *
 * 1–5 级向白色递进，用来做浅色填充与禁用态；7–10 级向黑色递进，用来做
 * 悬停、按下与深色文字。递进比例沿用 Arco 自身色板的视觉节奏。
 *
 * @param base - 第 6 级取值，即 Arco 的主色位。
 * @returns 长度为 10 的色阶，下标 0 对应 `-1`。
 */
export function ramp(base: Triple): Triple[] {
  const steps = [0.92, 0.8, 0.64, 0.44, 0.2]
  const darker = [0.18, 0.36, 0.54, 0.72]
  return [
    ...steps.map(t => mixTriple(base, WHITE, t)),
    base,
    ...darker.map(t => mixTriple(base, BLACK, t)),
  ]
}

/**
 * 把一条色阶序列化为 CSS 自定义属性声明。
 *
 * @param prefix - 属性名前缀，不含 `--`，例如 `primary`。
 * @param steps - 十级色阶。
 * @returns 每行一条、带两空格缩进与换行的声明文本。
 */
export function declareRamp(prefix: string, steps: readonly Triple[]): string {
  return steps.map((step, index) => `  --${prefix}-${index + 1}: ${step.join(',')};`).join('\n')
}
